// подстановки: {name}|без имени, {days}, {n}; без «{…}» и двойных пробелов в выводе
export function fill(line, ctx = {}) {
  const [withName, without] = String(line).split('|');
  let out = ctx.name ? withName.replace(/\{name\}/g, ctx.name) : (without ?? withName.replace(/\{name\}[,!]?\s*/g, ''));
  out = out.replace(/\{days\}/g, ctx.days ?? '').replace(/\{n\}/g, ctx.n ?? '');
  return out.replace(/\s{2,}/g, ' ').replace(/\s+([,.!?…])/g, '$1').trim();
}
// детерминированно на день: hash(день + группа + seed), без повтора последних 5 показанных (recent: ['group#i', …])
export function pick(group, { seed = '', day = dayKey(), recent = [], salt = '' } = {}) {
  const list = P[group] || []; if (!list.length) return { line: '', key: '' };
  let i = hash(day + group + seed + salt) % list.length;
  for (let k = 0; k < list.length && recent.includes(`${group}#${i}`); k++) i = (i + 1) % list.length;
  return { line: list[i], key: `${group}#${i}` };
}
